// Writes ../docs/tour-text-for-review.md from src/tour.json: every sentence a visitor can read, in tour order,
// so a priest can check it without opening the app. Anything marked "review": true is flagged. Edit the text
// in tour.json, then run `npm run text` again.
import { readFileSync, writeFileSync } from 'node:fs';

const tour = JSON.parse(readFileSync(new URL('../src/tour.json', import.meta.url), 'utf8'));
const flag = (o) => (o.review ? ' **[REVIEW]**' : '');
const note = (o) => (o.review && o.reviewNote ? `\n> Review note: ${o.reviewNote}\n` : '');
const itemFor = (name) => tour.items[name];
const L = [];
L.push('# Tour text for review', '');
L.push('Generated from `web/src/tour.json` by `npm run text` (in `web/`). Do not edit this file: change the text in tour.json and run it again.', '');
L.push('Items marked **[REVIEW]** were written with less certainty, or need a detail about this parish. Everything else is still open to correction.', '');

const flagged = [];
if (tour.church.review) flagged.push(['Intro screen', tour.church.reviewNote]);
tour.stops.forEach((s, i) => {
  if (s.review) flagged.push([`Stop ${i + 1}: ${s.title}`, s.reviewNote]);
  if (s.todo) flagged.push([`Stop ${i + 1}: ${s.title} (question)`, s.todo]);
});
for (const [k, it] of Object.entries(tour.items)) if (it.review) flagged.push([`${it.title} (\`${k}\`)`, it.reviewNote]);
L.push('## Marked for review', '');
flagged.forEach(([t, n]) => L.push(`- ${t}${n ? ': ' + n : ''}`));
L.push('');

L.push('## Intro screen' + flag(tour.church), '', `**${tour.church.name}**`, '', tour.church.tagline, '', tour.church.intro, note(tour.church));
const used = new Set();
tour.stops.forEach((s, i) => {
  L.push(`## ${i + 1}. ${s.title}${flag(s)}`, '', s.text, note(s));
  if (s.todo) L.push(`> Question for the parish: ${s.todo}`, '');
  for (const name of s.items) {
    const it = itemFor(name);
    if (!it) { L.push(`### ${name}`, '', '_No text yet._', ''); continue; }
    if (used.has(name)) { L.push(`- Also selectable here: ${it.title} (text above)`, ''); continue; }
    used.add(name);
    L.push(`### ${it.title}${flag(it)}`, '', `\`${name}\``, '', it.text, note(it));
  }
});
const rest = Object.keys(tour.items).filter((k) => !used.has(k));
if (rest.length) {
  L.push('## Items not listed at any stop', '');
  for (const k of rest) { const it = tour.items[k]; L.push(`### ${it.title}${flag(it)}`, '', `\`${k}\``, '', it.text, note(it)); }
}
const out = new URL('../../docs/tour-text-for-review.md', import.meta.url);
writeFileSync(out, L.join('\n').replace(/\n{3,}/g, '\n\n') + '\n');
console.log(`wrote docs/tour-text-for-review.md: ${tour.stops.length} stops, ${Object.keys(tour.items).length} items, ${flagged.length} marked for review`);
